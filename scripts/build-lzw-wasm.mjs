/**
 * Build the LZW WASM kernel, and embed it.
 *
 * Run:
 *   node scripts/build-lzw-wasm.mjs
 *
 * Needs a Rust toolchain with the wasm32 target, which almost nobody working on
 * this repo needs:
 *
 *   curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- \
 *     --profile minimal --target wasm32-unknown-unknown
 *
 * ## Why the artifact is committed
 *
 * CI, Vercel and anyone running `node scripts/lzw-test.mjs` must not need
 * cargo. So `native/lzw/lzw.wasm` is committed, and only someone changing
 * `native/lzw/src/lib.rs` runs this script. The .wasm is 1.4 KB; the argument
 * for keeping a binary out of a repo does not really apply at that size, and the
 * argument for a build that works on a clean checkout very much does.
 *
 * ## Why it is committed twice
 *
 * `native/lzw/lzw.wasm` is the artifact — the thing to diff, disassemble, or
 * hand to a Worker. `src/lib/geo/lzw-wasm.mjs` is the same bytes as base64 in an
 * ES module, and that is what the runtime actually loads.
 *
 * Embedding rather than `readFileSync` is not an aesthetic choice. The decoder
 * is imported by API routes that Next bundles and traces; a file read relative
 * to `import.meta.url` is exactly the kind of thing that resolves on a laptop
 * and 404s on a deployment, and it cannot work at all in the Cloudflare Worker
 * these kernels are meant to move into, which has no filesystem. Base64 costs
 * 33% of 1.4 KB and removes the entire class of problem.
 *
 * `scripts/lzw-test.mjs` asserts the two stay in step, so a rebuilt kernel that
 * was not re-embedded fails a test rather than shipping silently as the old one.
 */

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const crate = join(root, "native", "lzw");
const wasmPath = join(crate, "lzw.wasm");
const embedPath = join(root, "src", "lib", "geo", "lzw-wasm.mjs");

// Keep target/ inside the crate so one .gitignore line covers it, and so
// `rm -rf native/lzw/target` is the whole cleanup story on a disk-constrained
// machine. The debug artifacts are not small; the release .wasm is.
const target = join(crate, "target");

console.log("cargo build --release --target wasm32-unknown-unknown");
execFileSync("cargo", ["build", "--release", "--target", "wasm32-unknown-unknown"], {
  cwd: crate,
  stdio: "inherit",
  env: { ...process.env, CARGO_TARGET_DIR: target },
});

const built = join(target, "wasm32-unknown-unknown", "release", "lzw.wasm");
copyFileSync(built, wasmPath);

const bytes = readFileSync(wasmPath);

// Fail here rather than at runtime. A module that instantiates but is missing an
// export produces a TypeError deep inside a tile request, which reads as "the
// portal is broken" rather than "the kernel was renamed".
const exports = WebAssembly.Module.exports(new WebAssembly.Module(bytes)).map((e) => e.name);
for (const wanted of ["memory", "lzw_alloc", "lzw_reset", "lzw_decode"]) {
  if (!exports.includes(wanted)) {
    throw new Error(`native/lzw/lzw.wasm does not export ${wanted} (has: ${exports.join(", ")})`);
  }
}

const base64 = bytes.toString("base64");
mkdirSync(dirname(embedPath), { recursive: true });
writeFileSync(
  embedPath,
  `/**
 * The compiled LZW kernel, base64 encoded.
 *
 * GENERATED by scripts/build-lzw-wasm.mjs from native/lzw/src/lib.rs.
 * Do not edit: rebuild instead, or the source and the shipped kernel drift
 * apart with nothing to notice.
 *
 * ${bytes.length} bytes of WebAssembly. See the build script for why this is a
 * string in a module rather than a file read off disk.
 */

export const LZW_WASM_BASE64 =
  "${base64}";
`,
);

console.log(`native/lzw/lzw.wasm      ${bytes.length} bytes`);
console.log(`src/lib/geo/lzw-wasm.mjs ${base64.length} base64 characters`);
console.log("\nRemember to run: node scripts/lzw-test.mjs");
